import streamlit as st
import pandas as pd
import joblib
from pathlib import Path

model_path = Path(__file__).resolve().parent / "random_forest_final_model.pkl"
model = joblib.load(model_path)

st.set_page_config(page_title="Digital Wellbeing Analytics", page_icon="📱")
st.title("📱 Digital Wellbeing Analytics")
st.subheader("Smartphone Addiction Prediction System")
st.write("Enter your smartphone usage details to get a machine-learning prediction.")

st.header("Enter Your Smartphone Usage Details")

age = st.number_input("Age", min_value=10, max_value=100, value=21)
gender = st.selectbox("Gender", ["Male", "Female", "Other"], key="gender")
daily_screen_time = st.number_input("Daily Screen Time (hours)", min_value=0.0, max_value=24.0, value=8.0)
social_media_hours = st.number_input("Social Media Usage (hours)", min_value=0.0, max_value=24.0, value=4.0)
gaming_hours = st.number_input("Gaming Hours", min_value=0.0, max_value=24.0, value=2.0)
work_study_hours = st.number_input("Work/Study Hours", min_value=0.0, max_value=24.0, value=4.0)
sleep_hours = st.number_input("Sleep Hours", min_value=0.1, max_value=24.0, value=7.0)
notifications_per_day = st.number_input("Notifications Per Day", min_value=0, max_value=1000, value=150)
app_opens_per_day = st.number_input("App Opens Per Day", min_value=1, max_value=1000, value=100)
weekend_screen_time = st.number_input("Weekend Screen Time (hours)", min_value=0.0, max_value=24.0, value=10.0)
stress_level = st.selectbox("Stress Level", ["High", "Medium", "Low"], key="stress_level")
academic_work_impact = st.selectbox("Academic/Work Impact", ["Yes", "No"], key="academic_work_impact")

st.divider()

if st.button("🔍 Predict Smartphone Addiction", use_container_width=True):
    total_leisure_hours = social_media_hours + gaming_hours
    screen_to_sleep_ratio = daily_screen_time / sleep_hours
    weekend_screen_time_increase = weekend_screen_time - daily_screen_time
    notification_intensity = notifications_per_day / app_opens_per_day
    productive_time_ratio = work_study_hours / (work_study_hours + daily_screen_time)

    user_data = pd.DataFrame({
        "age": [age],
        "gender": [gender],
        "daily_screen_time_hours": [daily_screen_time],
        "social_media_hours": [social_media_hours],
        "gaming_hours": [gaming_hours],
        "work_study_hours": [work_study_hours],
        "sleep_hours": [sleep_hours],
        "notifications_per_day": [notifications_per_day],
        "app_opens_per_day": [app_opens_per_day],
        "weekend_screen_time": [weekend_screen_time],
        "stress_level": [stress_level],
        "academic_work_impact": [academic_work_impact],
        "total_leisure_hours": [total_leisure_hours],
        "screen_to_sleep_ratio": [screen_to_sleep_ratio],
        "weekend_screen_time_increase": [weekend_screen_time_increase],
        "notification_intensity": [notification_intensity],
        "productive_time_ratio": [productive_time_ratio]
    })

    prediction = model.predict(user_data)[0]
    probabilities = model.predict_proba(user_data)[0]

    st.divider()
    st.header("Prediction Result")

    if prediction == 1:
        st.error("⚠️ Likely Addicted")
    else:
        st.success("✅ Likely Not Addicted")

    col1, col2 = st.columns(2)

    with col1:
        st.metric("Not Addicted Probability", f"{probabilities[0] * 100:.2f}%")

    with col2:
        st.metric("Addicted Probability", f"{probabilities[1] * 100:.2f}%")

    st.write("Addicted Probability")
    st.progress(int(probabilities[1] * 100))

    st.info("This prediction is generated by a machine-learning model and is not a medical or psychological diagnosis.")